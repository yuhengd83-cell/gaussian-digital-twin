import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import zlib from 'node:zlib';
import path from 'node:path';
const root=new URL('../',import.meta.url);
const assetPath=file=>process.env.AGV_TEST_DATA_ROOT?path.join(process.env.AGV_TEST_DATA_ROOT,file):new URL('../'+file,import.meta.url);
const geo=JSON.parse(fs.readFileSync(assetPath('config/epoch30_georeference.json'),'utf-8'));
const scenes=JSON.parse(fs.readFileSync(new URL('../config/scenes.json',import.meta.url),'utf-8'));
const entry=scenes.models.find(m=>m.id===scenes.defaultModel);
assert.equal(entry.id,'epoch30_20261015');
assert.equal(geo.sceneFamily,'epoch30_20261015');
assert.equal(entry.splats,1739253);
const b=fs.readFileSync(assetPath(entry.url));
assert.equal(b.byteLength,29254747);
const hash=createHash('sha256').update(b).digest('hex');
assert.equal(hash,'e332130c5c8ae17babcf013d135108e63146f3115ede3509d8d9cb23ea5f1f13');
assert.equal(hash,geo.sourceSpzSha256);
const d=zlib.gunzipSync(b);
assert.equal(d.toString('ascii',0,4),'NGSP');
assert.equal(d.readUInt32LE(4),3);
assert.equal(d.readUInt32LE(8),geo.sourceSpzGaussianCount);
const other=scenes.models.find(m=>m.id==='park2_rear_20261019');
assert.ok(other && other.url==='models/park2_splat.spz');
assert.equal(other.identityStatus,'blocked','historical epoch30 bytes must not load as park2');
assert.equal(other.identityConflict.sha256,hash);
assert.equal(other.identityConflict.observedSplats,entry.splats);
assert.equal(other.identityConflict.declaredSplats,918596);
assert.notEqual(other.id,scenes.defaultModel);
console.log('EPOCH30_IDENTITY_PASS SHA256 bytes counts default and distinct old scene');
